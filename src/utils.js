/* =========================================================================
   ACCESSIBILITY & FORM VALIDATION (ADDED DURING REFACTOR)
   ========================================================================= */
if (typeof document !== 'undefined') {
  document.addEventListener('invalid', (e) => {
    if (!e.target || !e.target.setAttribute) return;
    e.target.setAttribute('aria-invalid', 'true');
    let err = e.target.nextElementSibling;
    if (!err || !err.classList.contains('error-text')) {
      err = document.createElement('span');
      err.className = 'error-text';
      err.id = (e.target.id || 'input-' + Math.random().toString(36).substr(2, 9)) + '-error';
      e.target.parentNode.insertBefore(err, e.target.nextSibling);
      e.target.setAttribute('aria-describedby', err.id);
    }
    err.textContent = e.target.validationMessage;
  }, true);

  document.addEventListener('input', (e) => {
    if (!e.target || !e.target.hasAttribute) return;
    if (e.target.hasAttribute('aria-invalid')) {
      if (e.target.checkValidity && e.target.checkValidity()) {
        e.target.removeAttribute('aria-invalid');
        const errId = e.target.getAttribute('aria-describedby');
        if (errId) {
          const err = document.getElementById(errId);
          if (err) err.remove();
        }
        e.target.removeAttribute('aria-describedby');
      } else {
        const errId = e.target.getAttribute('aria-describedby');
        if (errId) {
          const err = document.getElementById(errId);
          if (err && e.target.validationMessage) {
            err.textContent = e.target.validationMessage;
          }
        }
      }
    }
  });
}
